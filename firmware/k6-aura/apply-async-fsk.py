#!/usr/bin/env python3
"""Opt-in level 28 asynchronous native 4800-baud Data transport."""
from pathlib import Path
p=Path(__file__).parent/'build/aura-fd6818b-port/src/app/pager.rs'
s=p.read_text()
def add(old,new):
    global s
    if new in s:return
    if s.count(old)!=1:raise ValueError(old)
    s=s.replace(old,new,1)
add('        pub resource_read: unsafe extern "C" fn(u32, u32, *mut u8, u32) -> i32,',
    '        pub resource_read: unsafe extern "C" fn(u32, u32, *mut u8, u32) -> i32,\n        pub fsk_async: unsafe extern "C" fn(u32,*const u16,u32) -> i32,')
add('    resource_read: mod_resource_read,','    resource_read: mod_resource_read,\n    fsk_async: mod_fsk_async,')
add('unsafe extern "C" fn mod_tx_off() {','unsafe extern "C" fn mod_tx_off() {\n    #[cfg(k6_async_fsk)]\n    unsafe { async_fsk_cleanup(); }')
# On repeat builds the older level expression is regenerated by the resource overlay.
add('level: if cfg!(all(k6_live_serial,k6_ram0_balanced,k6_user_store,feature="spilib",feature="lean",feature="blowfang-host")) { 27 }',
    'level: if cfg!(k6_async_fsk) { 28 } else if cfg!(all(k6_live_serial,k6_ram0_balanced,k6_user_store,feature="spilib",feature="lean",feature="blowfang-host")) { 27 }')
add('*arena::base().add(12) == 27','matches!(*arena::base().add(12),27|28)')
# Existing blocking service cannot start another packet while async owns RF.
add('    if fast { return unsafe {mod_fsk_tx4800(ptr)}; }',
    '    #[cfg(k6_async_fsk)]\n    if unsafe{ASYNC_ACTIVE} {return -1;}\n    if fast { return unsafe {mod_fsk_tx4800(ptr)}; }')
body=r'''
// ASYNC_FSK_BEGIN
// Only the foreground module owns this state. The independent watchdog
// stays armed; all exits through mod_tx_off invalidate the packet lease.
#[cfg(k6_async_fsk)]
static mut ASYNC_ACTIVE: bool=false;
#[cfg(k6_async_fsk)]
static mut ASYNC_SNAPSHOT: bool=false;
#[cfg(k6_async_fsk)]
static mut ASYNC_DEADLINE: u32=0;
#[cfg(k6_async_fsk)]
static mut ASYNC_SAVED: [u16;9]=[0;9];
#[cfg(k6_async_fsk)]
const ASYNC_REGS:[u8;9]=[0x3f,0x59,0x58,0x70,0x72,0x5a,0x5b,0x5c,0x5d];
#[cfg(k6_async_fsk)]
unsafe fn async_fsk_valid()->bool{
    mod_tx_guard();
    let c=&*addr_of!(MOD_CTX);
    !c.app.is_null() && c.tx && mod_key_down()==0 &&
        mod_cancel_poll()!=1
}
#[cfg(k6_async_fsk)]
unsafe fn async_fsk_write(r:u8,v:u16)->bool{
    mod_tx_guard();
    if !(*addr_of!(MOD_CTX)).tx{return false;}
    let (app,syst)=mod_ctx();
    app.radio.fd6818.reg_write(syst,r,v);true
}
#[cfg(k6_async_fsk)]
unsafe fn async_fsk_cleanup(){
    ASYNC_ACTIVE=false;
    if !ASYNC_SNAPSHOT{return;}
    ASYNC_SNAPSHOT=false;
    if !(*addr_of!(MOD_CTX)).tx{return;}
    let (app,syst)=mod_ctx();
    app.radio.cw_carrier_off(syst);
    for (r,v) in [(0x59,0x00f8),(0x3f,0),(0x02,0)]{app.radio.fd6818.reg_write(syst,r,v);}
    for i in (0..9).rev(){app.radio.fd6818.reg_write(syst,ASYNC_REGS[i],ASYNC_SAVED[i]);}
}
#[cfg(k6_async_fsk)]
unsafe fn async_fsk_fail()->i32{
    mod_tx_off();-2
}
// Start returns 0 once FIFO is loaded and transmission started.
// Poll returns 0 while busy, 1 only on observed hardware completion.
// Abort always drops the lease; no retry. No software delay loop.
#[cfg(k6_async_fsk)]
unsafe extern "C" fn mod_fsk_async(op:u32,ptr:*const u16,n:u32)->i32{
    if !full_module_stack() || *arena::base().add(12)!=28{return -1;}
    if op==2 {mod_tx_off();return 0;}
    if op==0 {
        if ASYNC_ACTIVE{return async_fsk_fail();}
        if n!=33||ptr.is_null()||ptr as usize&1!=0||
            (ptr as usize)<(*addr_of!(MOD_CTX)).scratch||
            (ptr as usize).saturating_add(66)>scratch_end(){return async_fsk_fail();}
        if !async_fsk_valid()||mod_tx_pa(0)!=0||mod_fd_read(0)!=0x4829{return async_fsk_fail();}
        const VALS:[u16;9]=[0x8000,0x00f8,0x00e1,0x0095,0xc194,0x076b,0x3e36,0x5625,0x4100];
        for i in 0..9 {ASYNC_SAVED[i]=mod_fd_read(ASYNC_REGS[i]);}
        if ASYNC_SAVED[0]&0xa000!=0||ASYNC_SAVED[1]&0x0800!=0{return async_fsk_fail();}
        ASYNC_SNAPSHOT=true;
        if !async_fsk_write(0x59,0x00f8)||!async_fsk_write(0x02,0){return async_fsk_fail();}
        for i in 0..9 {if !async_fsk_write(ASYNC_REGS[i],VALS[i]){return async_fsk_fail();}}
        if !async_fsk_write(0x59,0x80f8)||!async_fsk_write(0x59,0x00f8){return async_fsk_fail();}
        for i in 0..33 {
            if !async_fsk_valid()||!async_fsk_write(0x5f,ptr.add(i).read()){return async_fsk_fail();}
        }
        if !async_fsk_valid()||mod_fd_read(0x0c)&1!=0||mod_tx_pa(1)!=0{return async_fsk_fail();}
        if !async_fsk_write(0x59,0x08f8){return async_fsk_fail();}
        ASYNC_DEADLINE=mod_tick().wrapping_add(7000);
        ASYNC_ACTIVE=true;return 0;
    }
    if op!=1||!ASYNC_ACTIVE||!async_fsk_valid()||mod_fd_read(0x30)&2==0||
        mod_tick().wrapping_sub(ASYNC_DEADLINE)<0x80000000{return async_fsk_fail();}
    if mod_fd_read(0x0c)&1==0{return 0;}
    if mod_tx_pa(0)!=0{return async_fsk_fail();}
    for (r,v) in [(0x59,0x00f8),(0x3f,0),(0x02,0)] {
        if !async_fsk_write(r,v){return async_fsk_fail();}
    }
    for i in (0..9).rev(){
        if !async_fsk_write(ASYNC_REGS[i],ASYNC_SAVED[i]){return async_fsk_fail();}
    }
    mod_tx_guard();
    if !(*addr_of!(MOD_CTX)).tx{return async_fsk_fail();}
    ASYNC_ACTIVE=false;ASYNC_SNAPSHOT=false;1
}
#[cfg(not(k6_async_fsk))]
unsafe extern "C" fn mod_fsk_async(_:u32,_:*const u16,_:u32)->i32{-1}
// ASYNC_FSK_END
'''
if '// ASYNC_FSK_BEGIN' in s:
    a=s.index('// ASYNC_FSK_BEGIN');b=s.index('// ASYNC_FSK_END',a)+len('// ASYNC_FSK_END')
    s=s[:a]+body.strip()+s[b:]
else:s+=body
p.write_text(s)
