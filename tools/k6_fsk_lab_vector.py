#!/usr/bin/env python3
"""Create deterministic native-FSK lab FIFO vectors (host only; no radio).

The intended bit sequence is MSB-first within each byte, lower byte first
per 16-bit FIFO word. Hardware FSK may add its own preamble/sync sequence:
these vectors describe only the explicit FIFO payload.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import random
from pathlib import Path

SUPPORTED_BAUD = (1200, 2400, 3600, 4800)
MIN_WORDS = 32
MAX_WORDS = 64
BENCH_FREQUENCY_HZ = 433_500_000
NATIVE_BAUD_BASE_WORD = 0x3065


def words_from_bits(bits: str) -> tuple[int, ...]:
    if not bits or any(c not in "01" for c in bits) or len(bits) % 16:
        raise ValueError("bit sequence must contain 0/1 and whole 16-bit words")
    words = []
    for i in range(0, len(bits), 16):
        b0 = int(bits[i:i+8], 2)
        b1 = int(bits[i+8:i+16], 2)
        words.append(b0 | b1 << 8)
    return tuple(words)


def bits_from_words(words: tuple[int, ...]) -> str:
    return "".join(f"{w & 255:08b}{w >> 8:08b}" for w in words)


def make_probe_vector(*, word_count=64, seed=0xACE1,
                      data_bits: str | None = None) -> tuple[tuple[int, ...], list[dict]]:
    if not isinstance(word_count, int) or not MIN_WORDS <= word_count <= MAX_WORDS:
        raise ValueError("word count must be 32 through 64")
    if not 0 <= seed <= 0xFFFFFFFF:
        raise ValueError("seed must be a 32-bit unsigned integer")
    if data_bits is not None:
        bits = "".join(data_bits.split())
        values = words_from_bits(bits)
        if len(values) != word_count:
            raise ValueError("custom bits must match requested word count exactly")
        return values, [dict(name="custom", start_bit=0, bits=len(bits))]

    # Sacrificial alternating preamble deliberately included in the
    # *explicit* FIFO data, distinct from chip-generated framing.
    lead = 16
    diagnostic = [0]*4 + [0xFFFF]*4 + [0x0F0F]*4 + [0xF0F0]*4
    if word_count < lead + len(diagnostic):
        raise ValueError("need space for the preamble and diagnostic runs")
    prng = random.Random(seed)
    tail = [prng.getrandbits(16) for _ in range(word_count-lead-len(diagnostic))]
    values = tuple([0x5555]*lead + diagnostic + tail)
    segments = [
        dict(name="sacrificial_alternating_payload", start_bit=0, bits=lead*16),
        dict(name="zero_hold", start_bit=lead*16, bits=4*16),
        dict(name="one_hold", start_bit=(lead+4)*16, bits=4*16),
        dict(name="repeating_nibbles_0f", start_bit=(lead+8)*16, bits=4*16),
        dict(name="repeating_nibbles_f0", start_bit=(lead+12)*16, bits=4*16),
        dict(name="seeded_tail", start_bit=(lead+16)*16,
             bits=len(tail)*16)
    ]
    return values, segments


def build_vector(*, word_count=64, seed=0xACE1, data_bits=None,
                 baud=4800, gain=48, frequency_hz=BENCH_FREQUENCY_HZ) -> tuple[str, dict]:
    if baud not in SUPPORTED_BAUD:
        raise ValueError("supported native bit rates: 1200, 2400, 3600, 4800")
    if not 16 <= gain <= 96:
        raise ValueError("FSK lab gain must be in the existing 16..96 test range")
    if frequency_hz != BENCH_FREQUENCY_HZ:
        raise ValueError("initial conducted bench vector is fixed at 433500000 Hz")
    values, segments = make_probe_vector(word_count=word_count, seed=seed,
                                         data_bits=data_bits)
    wire_bytes = b"".join(w.to_bytes(2, "little") for w in values)
    h = hashlib.sha256(wire_bytes).hexdigest()
    baud_word = round(NATIVE_BAUD_BASE_WORD * baud / 1200)
    if not 0 < baud_word <= 0xFFFF:
        raise ValueError("FSK baud word does not fit hardware register")
    lines = [
        "/* GENERATED by tools/k6_fsk_lab_vector.py -- radio TX is disabled by default.",
        "   Payload only; chip may insert its own preamble/sync. DO NOT edit by hand.",
        f"   sha256 of 16-bit words in little-endian order: {h} */",
        "#ifndef FLUX_FSK_LAB_VECTOR_H",
        "#define FLUX_FSK_LAB_VECTOR_H",
        "#include <stdint.h>",
        f"#define FSK_LAB_VECTOR_WORDS {len(values)}u",
        f"#define FSK_LAB_VECTOR_BITS {len(values)*16}u",
        f"#define FSK_LAB_BAUD {baud}u",
        f"#define FSK_LAB_BAUD_WORD 0x{baud_word:04x}u",
        f"#define FSK_LAB_GAIN {gain}u",
        f"#define FSK_LAB_FREQUENCY_HZ {frequency_hz}u",
        "static const uint16_t fsk_lab_words[FSK_LAB_VECTOR_WORDS] = {"
    ]
    for i in range(0, len(values), 8):
        lines.append("    " + ", ".join(f"0x{w:04x}u" for w in values[i:i+8]) + ",")
    lines.extend(["};", "#endif", ""])
    report = {
        "project": "Flux", "purpose": "known native 2-FSK FIFO payload",
        "offline_generated": True, "transmitted": False,
        "physical_hardware_validated": False,
        "chip_id_required": "0x4829", "frequency_hz": frequency_hz,
        "native_baud": baud, "baud_register_72": baud_word,
        "tone_fsk_gain_register_70": 0x0080 | gain,
        "reg_40": "unchanged; no unverified deviation override",
        "payload_words": len(values), "payload_bits": len(values)*16,
        "payload_duration_ms_nominal": round(len(values)*16*1000/baud, 3),
        "payload_bytes_hex": wire_bytes.hex(),
        "payload_bits_msb_each_byte_lower_byte_first": bits_from_words(values),
        "payload_sha256_le_words": h,
        "seed": seed if data_bits is None else None,
        "segments": segments,
        "chip_generated_preamble_and_sync": "uncharacterized; not included in payload_bits",
        "caveats": [
            "A benchmark header is NOT a valid or authorized transmitter by itself.",
            "Default C module refuses TX without explicit fixture, watchdog and enabled build.",
            "The PDM frequency trajectory and RF phase are NOT established by bit ordering alone.",
            "Actual deviation depends on undocumented FD6818B behavior; REG_40 is not altered."
        ]
    }
    return "\n".join(lines), report


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--header", required=True, type=Path)
    p.add_argument("--manifest", required=True, type=Path)
    p.add_argument("--words", type=int, default=64)
    p.add_argument("--baud", type=int, default=4800)
    p.add_argument("--gain", type=int, default=48)
    p.add_argument("--seed", type=lambda s: int(s, 0), default=0xACE1)
    p.add_argument("--frequency-hz", type=int, default=BENCH_FREQUENCY_HZ)
    p.add_argument("--bits-file", type=Path, help="custom 0/1 bits (exact --words * 16)")
    p.add_argument("--overwrite", action="store_true",
                   help="explicitly replace the generated header and manifest")
    args = p.parse_args(argv)
    if args.header.resolve() == args.manifest.resolve():
        p.error("header and manifest must be different files")
    if not args.overwrite and (args.header.exists() or args.manifest.exists()):
        p.error("existing output: supply --overwrite to regenerate deliberately")
    try:
        bits = args.bits_file.read_text() if args.bits_file else None
        header, report = build_vector(word_count=args.words, seed=args.seed,
                                     data_bits=bits, baud=args.baud, gain=args.gain,
                                     frequency_hz=args.frequency_hz)
    except (ValueError, OSError) as e:
        p.error(str(e))
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header)
    args.manifest.write_text(json.dumps(report, indent=2)+"\n")
    print(f"Offline vector: {report['payload_words']} words at {args.baud} bits/s "
          f"({report['payload_duration_ms_nominal']} ms nominal), sha256 "
          f"{report['payload_sha256_le_words']}")
    print(f"Header: {args.header}\nManifest: {args.manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
