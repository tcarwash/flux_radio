#!/usr/bin/env python3
"""Actual ARM Sotto synthetic-PCM module -> modeled K6 FSK -> compiled RX.

Unlike the earlier GP0 matrix, this executes the *synthetic RF module itself*.
Audio is generated by the real ARM module's time-paced producer, not injected
into a physical microphone or generated on the host at run time. The matching
host-generated PCM is used solely as an independent reference oracle.
Entirely offline: no serial connection, PTT, radio or RF is accessed.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:sys.path.insert(0,str(ROOT))
import numpy as np
from sim.k6emu.rf.virtual_link import Channel
from tools.k6_sotto_module import build
from tools.k6_sotto_virtual_link import prepare,trial

PROFILES=('silence','multitone','chirp','bursts')
N_BLOCKS=104
N_SAMPLES=N_BLOCKS*80
EMU_FREQ=433500000

def _triangle(phase:int)->int:
    v=phase>>20
    return (v if v<2048 else 4095-v).__sub__(1024)*6


def pcm(profile:int)->np.ndarray:
    if isinstance(profile,bool) or profile not in range(len(PROFILES)):
        raise ValueError('invalid synthetic PCM profile')
    phase1=phase2=0
    chirp=171798692
    samples=[]
    for block in range(N_BLOCKS):
        for _ in range(80):
            if profile==0:
                samples.append(0)
                continue
            phase1=(phase1+chirp)&0xffffffff
            if profile==2:chirp=(chirp+167772)&0xffffffff
            v=_triangle(phase1)
            if profile==1:
                phase2=(phase2+467077693)&0xffffffff
                p=_triangle(phase2)
                # C99 integer divide truncates toward zero, unlike Python //.
                v+=(abs(p)//3)*(1 if p>=0 else -1)
            if profile==3 and (block//8)&1:v=0
            samples.append(v)
    a=np.asarray(samples,dtype='<i2')
    assert len(a)==N_SAMPLES
    return a


def run(out:Path,*,profiles=range(4),variants=('original','optimized'),cpi_values=(1.7,2.5)):
    out=out.resolve();out.mkdir(parents=True,exist_ok=True)
    results=[]
    for profile in profiles:
        directory=out/PROFILES[profile]
        directory.mkdir(parents=True,exist_ok=True)
        a=prepare(ROOT,directory,pcm=pcm(profile),gp0=True)
        for variant in variants:
            optimized=variant=='optimized'
            if variant not in ('original','optimized'):raise ValueError(variant)
            code,entry=build(host_resources=True,synthetic_tx=True,
                            synth_profile=profile,synth_hz=EMU_FREQ,
                            fast_div=optimized,fast_history_copy=optimized,
                            fast_cb_pair=optimized,fast_lag_pair=optimized)
            assert len(code)<=9784 and entry==a['entry']
            candidate={**a,'code':code,'entry':entry}
            for cpi in cpi_values:
                r=trial(candidate,Channel(),cpi=cpi,spi_us=6.19212962962963,
                        spi_byte_us=.9403935185185185,fd_us=60,
                        fsk_cooperative_model=True)
                passed=(r['module_return']==26 and r['codec_frames']==26 and r['codec_exact']
                        and r['session']['complete'] and r['session']['valid']==6
                        and r['session']['invalid']==0 and r['wire_decoder_agrees']
                        and r['received']==6 and not r['tx']['active']
                        and not any(r['tx'][x] for x in ('aborted','rejected','overflows')))
                assert not r['tx']['active'],'a failed simulated module must not leave TX keyed'
                line={
                    'profile':PROFILES[profile], 'variant':variant, 'cpi':cpi,
                    'passed':passed,'module_sha256':hashlib.sha256(code).hexdigest(),
                    'module_size':len(code),'scratch_margin':14976-1040-24-len(code)-4080,
                    'return':r['module_return'],'codec_frames':r['codec_frames'],
                    'codec_exact':r['codec_exact'],'session_complete':r['session']['complete'],
                    'session_valid':r['session']['valid'],'session_invalid':r['session']['invalid'],
                    'rf_received':r['received'],'tx_end_keyed':r['tx']['active'],
                    'telemetry':r['logs'],
                    'sim_wall_s':r['wall_seconds'],
                }
                results.append(line)
                print(f"{PROFILES[profile]:9s} {variant:9s} CPI {cpi:.1f} {'PASS' if passed else 'FAIL'} "
                      f"encoded={r['codec_frames']} packets={r['session']['valid']} "
                      f"ret={r['module_return']} logs={r['logs']}",flush=True)
    payload={
        'hardware_test':False, 'description':'Actual ARM synthetic PCM module with modeled RF and compiled receiver',
        'profile_names':PROFILES,'sample_count':N_SAMPLES,'sample_rate_hz':8000,
        'virtual_frequency_hz':EMU_FREQ,
        'host_cpi_parameters':list(cpi_values),'cases':results,
    }
    (out/'report.json').write_text(json.dumps(payload,indent=2)+'\n')
    return payload

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out',type=Path,required=True)
    a=p.parse_args()
    r=run(a.out)
    print('TEST_MATRIX',sum(x['passed'] for x in r['cases']),len(r['cases']),flush=True)
