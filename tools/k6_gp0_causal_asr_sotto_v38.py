#!/usr/bin/env python3
"""Compare local ASR word errors for noisy and preamble-denoised GP0 speech.

This is a follow-on readability proxy to the causal-frame PESQ/ESTOI sweep.
It requires a locally cached faster-whisper model and never downloads one.
The reference transcript is generated by the same recognizer from clean speech,
so WER is comparative evidence, not ground-truth transcription or listener data.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import tempfile
from pathlib import Path

import numpy as np
from faster_whisper import WhisperModel

from k6_gp0_causal_denoise_sotto_v38 import (
    FS, METHODS as MASK_METHODS, PREAMBLE_SEED_OFFSET, causal_denoise,
)
from k6_gp0_noise_sotto_v38_study import (
    INPUT_VPP, SAMPLE_ROOT, SEEDS, VOICE_IDS, build_codec, encode_decode,
    read_flac, resample_poly,
)
from rfsim.k6_mic import OFF_PCM_RMS_FS, generate_gp0_noise, k6_gp0_pcm
from k6_sotto_fidelity_previews import normalize_for_audition

PREAMBLE_MS = 500
BEAM_SIZE = 1


def words(text: str) -> list[str]:
    return re.findall(r"[a-z0-9]+(?:'[a-z0-9]+)?", text.lower())


def wer(reference: list[str], candidate: list[str]) -> float:
    prev = list(range(len(candidate) + 1))
    for i, ref_word in enumerate(reference, 1):
        row = [i]
        for j, hyp_word in enumerate(candidate, 1):
            row.append(min(row[-1] + 1, prev[j] + 1,
                           prev[j - 1] + (ref_word != hyp_word)))
        prev = row
    return prev[-1] / max(len(reference), 1)


def transcribe(model, audio8: np.ndarray) -> list[str]:
    audio16 = resample_poly(audio8.astype(np.float32), 2, 1).astype(np.float32)
    audio16 = np.clip(audio16, -.999, .999)
    segments, _ = model.transcribe(audio16, language="en", beam_size=BEAM_SIZE,
                                   condition_on_previous_text=False)
    return words(" ".join(segment.text for segment in segments))


def matched_audio(x: np.ndarray, rms: float) -> np.ndarray:
    samples, _ = normalize_for_audition(x, rms)
    return samples.astype(np.float64) / 32768.0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-path", type=Path, required=True,
                        help="local faster-whisper base.en CTranslate2 directory")
    parser.add_argument("--input-vpp", type=float, choices=INPUT_VPP, nargs="+",
                        default=list(INPUT_VPP), help="modeled source-level scenarios to evaluate")
    parser.add_argument("--methods", choices=MASK_METHODS, nargs="+",
                        default=list(MASK_METHODS), help="causal masks to compare")
    parser.add_argument("--noise-scales", type=float, nargs="+", default=[1.0],
                        help="multipliers for the preamble noise-power estimate")
    parser.add_argument("--mask-floors", type=float, nargs="+", default=[0.05],
                        help="minimum gain values")
    parser.add_argument("--json-out", type=Path, required=True)
    args = parser.parse_args()
    if args.json_out.exists():
        parser.error("refuse overwrite existing report")
    if not (args.model_path / "model.bin").is_file():
        parser.error("model path must exist locally and contain model.bin")
    os.environ["HF_HUB_OFFLINE"] = "1"
    os.environ["HF_DATASETS_OFFLINE"] = "1"
    model = WhisperModel(str(args.model_path), device="cpu", compute_type="int8",
                         local_files_only=True, cpu_threads=4)
    report = {
        "schema": 1,
        "offline_only": True,
        "asr_model": "faster-whisper base.en, local CTranslate2 model, CPU int8, beam 1",
        "reference": "same ASR model transcript from clean 8kHz-downsampled speech (pseudo-reference)",
        "conditions": {},
        "methods": list(args.methods),
        "input_vpp_scenarios": list(args.input_vpp),
        "method_parameters": {"preamble_ms": PREAMBLE_MS,
                   "frame_lookahead_ms": 256 * 1000 / FS,
                   "noise_preamble_seed_offset": PREAMBLE_SEED_OFFSET,
                   "noise_scales": args.noise_scales,
                   "mask_floors": args.mask_floors},
        "limitations": [
            "The GP0 noise and test levels are statistical model inputs, not physical speech captures or calibrated speech SPL.",
            "ASR WER against a same-model pseudo-reference is only a comparative proxy, not human intelligibility.",
            "Mask selection is only a small sweep at fixed 500ms preamble; alpha, floor and tracker tuning are not exhausted.",
            "Host CPU processing and 32ms frame lookahead are not K6 MCU or end-to-end radio qualifications.",
            "The experiment omits the Sotto 4-8kHz hiss band and radio/channel impairments.",
        ],
    }
    with tempfile.TemporaryDirectory(prefix="gp0-causal-asr-v38-") as td:
        temp = Path(td)
        encoder, decoder = build_codec(temp)
        for voice in VOICE_IDS:
            original16 = read_flac(SAMPLE_ROOT / f"librispeech_{voice}__original16.flac", 16000)
            original = resample_poly(original16, 1, 2)
            reference_words = transcribe(model, original)
            peak = float(np.max(np.abs(original)))
            normalized = original / peak
            for vpp in args.input_vpp:
                key = f"{voice}__{vpp:.3f}Vpp"
                clean = k6_gp0_pcm(normalized, input_vpp=vpp, noise_rms_fs=0,
                                   response="measured", clip=True)
                clean_decoded = encode_decode(encoder, decoder, clean, temp, key + "-clean")
                target_rms = float(np.std(clean_decoded))
                clean_words = transcribe(model, matched_audio(clean_decoded, target_rms))
                rows = []
                for seed in SEEDS:
                    noisy = k6_gp0_pcm(normalized, input_vpp=vpp,
                                       noise_rms_fs=OFF_PCM_RMS_FS, seed=seed,
                                       response="measured", noise_model="banded", clip=True)
                    preamble = generate_gp0_noise(
                        FS * PREAMBLE_MS // 1000,
                        seed=seed + PREAMBLE_SEED_OFFSET,
                        model="banded", rms_fs=OFF_PCM_RMS_FS)
                    noisy_decoded = encode_decode(encoder, decoder, noisy, temp,
                                                  f"{key}-noisy-{seed}")
                    noisy_words = transcribe(model, matched_audio(noisy_decoded, target_rms))
                    seed_row = {
                        "seed": seed,
                        "noisy_word_count": len(noisy_words),
                        "noisy_wer": round(wer(reference_words, noisy_words), 4),
                        "masks": {},
                    }
                    for method in args.methods:
                        for scale in args.noise_scales:
                            for floor in args.mask_floors:
                                setting = f"{method}/scale={scale:g}/floor={floor:g}"
                                stem = setting.replace("/", "-").replace("=", "")
                                filtered = causal_denoise(noisy, preamble, method,
                                                          noise_scale=scale, mask_floor=floor)
                                filtered_decoded = encode_decode(encoder, decoder, filtered, temp,
                                                                 f"{key}-{stem}-{seed}")
                                filtered_words = transcribe(model, matched_audio(filtered_decoded, target_rms))
                                seed_row["masks"][setting] = {
                                    "word_count": len(filtered_words),
                                    "wer": round(wer(reference_words, filtered_words), 4),
                                }
                    rows.append(seed_row)
                report["conditions"][key] = {
                    "reference_word_count": len(reference_words),
                    "clean_codec_word_count": len(clean_words),
                    "clean_codec_wer": round(wer(reference_words, clean_words), 4),
                    "noise_seeds": rows,
                }
                print(f"{key}: clean WER {report['conditions'][key]['clean_codec_wer']:.3f}; "
                      f"noisy {np.mean([x['noisy_wer'] for x in rows]):.3f}; "
                      f"masks " + ", ".join(
                          f"{method}/s{scale:g}/f{floor:g} "
                          f"{np.mean([x['masks'][f'{method}/scale={scale:g}/floor={floor:g}']['wer'] for x in rows]):.3f}"
                          for method in args.methods for scale in args.noise_scales
                          for floor in args.mask_floors), flush=True)

    report["summary"] = {}
    for vpp in args.input_vpp:
        suffix = f"{vpp:.3f}Vpp"
        rows = [value for key, value in report["conditions"].items() if key.endswith(suffix)]
        noisy = [x["noisy_wer"] for row in rows for x in row["noise_seeds"]]
        settings = [f"{method}/scale={scale:g}/floor={floor:g}"
                    for method in args.methods for scale in args.noise_scales
                    for floor in args.mask_floors]
        filtered = {setting: [x["masks"][setting]["wer"] for row in rows
                              for x in row["noise_seeds"]] for setting in settings}
        clean = [row["clean_codec_wer"] for row in rows]
        report["summary"][suffix] = {
            "mean_clean_codec_wer": round(float(np.mean(clean)), 4),
            "mean_noisy_wer": round(float(np.mean(noisy)), 4),
            "case_count": len(noisy),
            "masks": {},
        }
        for setting, values in filtered.items():
            report["summary"][suffix]["masks"][setting] = {
                "mean_wer": round(float(np.mean(values)), 4),
                "mean_wer_delta_vs_noisy": round(float(np.mean(np.asarray(values) - np.asarray(noisy))), 4),
                "cases_improved_vs_noisy": int(sum(b < a for a, b in zip(noisy, values))),
            }
    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    with args.json_out.open("x") as output:
        json.dump(report, output, indent=2, sort_keys=True)
        output.write("\n")
    print(json.dumps(report["summary"], indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
