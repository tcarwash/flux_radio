#!/usr/bin/env python3
"""Flux Whisper8 v0: *non-Olivia-compatible* eight-tone FM-audio modem reference.

No radio access. Generates PCM audio for a conventional FM receiver / SDR
discriminator and deterministic REG_71 words for a future guarded K6 test.
Olivia 8/250 shares the tone count/spacing but NOT this framing or FEC.
"""
from __future__ import annotations

import argparse
import binascii
import json
import math
import wave
from pathlib import Path

import numpy as np

SAMPLE_RATE = 8000
SAMPLES_PER_SYMBOL = 256
SYMBOL_RATE = SAMPLE_RATE / SAMPLES_PER_SYMBOL  # 31.25 symbols/s
TONE_SPACING_HZ = SYMBOL_RATE
BASE_HZ = 1125.0  # exactly bin 36 in each 256-sample FFT
TONES_HZ = tuple(BASE_HZ + i * TONE_SPACING_HZ for i in range(8))
FFT_TONE_BINS = tuple(range(36, 44))
PREAMBLE = (0, 7) * 6
SYNC = (7, 2, 5, 0, 3, 6, 1, 4, 7, 0, 6, 2)
MAX_BYTES = 48
FIXTURE_HOLDOUT = (1, 4, 6, 2, 7, 0, 3, 5)
FIXTURE = PREAMBLE + SYNC + FIXTURE_HOLDOUT


def reg71_word(hz: float) -> int:
    # Existing Flux K6 TX15 tone-oscillator conversion: k6/mod/tonewr.c.
    return int(hz * 1032444 / 100000)


def fixture_header() -> str:
    words = [reg71_word(TONES_HZ[s]) for s in FIXTURE]
    ids = ", ".join(str(s) for s in FIXTURE)
    registers = ", ".join(str(w) for w in words)
    return (
        "/* Generated by tools/k6_whisper8.py --header; never hand-edit. */\n"
        "#ifndef FLUX_WHISPER8_FIXTURE_H\n#define FLUX_WHISPER8_FIXTURE_H\n"
        "#define W8_FIXTURE_COUNT 32u\n"
        "static const unsigned char w8_fixture_ids[W8_FIXTURE_COUNT] = {" + ids + "};\n"
        "static const unsigned short w8_fixture_words[W8_FIXTURE_COUNT] = {" + registers + "};\n"
        "#endif\n"
    )


def bits_from_bytes(raw: bytes) -> list[int]:
    return [(byte >> shift) & 1 for byte in raw for shift in range(7, -1, -1)]


def bytes_from_bits(bits: list[int]) -> bytes:
    if len(bits) % 8:
        raise ValueError("bit count is not a multiple of eight")
    return bytes(
        sum(bits[pos + b] << (7 - b) for b in range(8))
        for pos in range(0, len(bits), 8)
    )


def uncoded_tones(raw: bytes) -> list[int]:
    bits = bits_from_bytes(raw)
    bits.extend([0] * (-len(bits) % 3))
    return [
        (bits[i] << 2) | (bits[i + 1] << 1) | bits[i + 2]
        for i in range(0, len(bits), 3)
    ]


def packet_symbols(payload: bytes) -> tuple[int, ...]:
    if len(payload) > MAX_BYTES:
        raise ValueError(f"payload exceeds {MAX_BYTES} bytes")
    raw = bytes([len(payload)]) + payload
    crc = binascii.crc_hqx(raw, 0xFFFF)
    raw += crc.to_bytes(2, "big")
    # Explicit, simple repetition-3 FEC; *not* Olivia's Walsh/sequence FEC.
    data = tuple(tone for tone in uncoded_tones(raw) for _ in range(3))
    return PREAMBLE + SYNC + data


def majority3(a: int, b: int, c: int) -> int:
    # A single incorrect tone ID in a triple is corrected.
    return a if a == b or a == c else b if b == c else a


def decode_symbols(symbols: tuple[int, ...] | list[int]) -> bytes:
    if tuple(symbols[: len(PREAMBLE)]) != PREAMBLE:
        raise ValueError("preamble mismatch")
    offset = len(PREAMBLE)
    if tuple(symbols[offset : offset + len(SYNC)]) != SYNC:
        raise ValueError("sync mismatch")
    data = symbols[offset + len(SYNC) :]
    if len(data) < 9:
        raise ValueError("truncated length field")

    def raw_bytes(n: int) -> bytes:
        need = 3 * math.ceil(n * 8 / 3)
        if len(data) < need:
            raise ValueError("truncated coded payload")
        tones = [majority3(*data[i : i + 3]) for i in range(0, need, 3)]
        bits = [bit for t in tones for bit in ((t >> 2) & 1, (t >> 1) & 1, t & 1)]
        return bytes_from_bits(bits[: n * 8])

    length = raw_bytes(1)[0]
    if length > MAX_BYTES:
        raise ValueError("invalid payload length")
    raw = raw_bytes(1 + length + 2)
    if binascii.crc_hqx(raw[:-2], 0xFFFF) != int.from_bytes(raw[-2:], "big"):
        raise ValueError("CRC16 mismatch")
    return raw[1:-2]


def render_audio(symbols: tuple[int, ...] | list[int], *, level: float = 0.75,
                 sample_rate: int = SAMPLE_RATE, prepad_samples: int = 0,
                 snr_db: float | None = None, seed: int = 7) -> np.ndarray:
    if sample_rate != SAMPLE_RATE:
        raise ValueError("this v0 reference is pinned to 8000 Hz")
    if any(t not in range(8) for t in symbols):
        raise ValueError("tone ID must be in 0..7")
    freqs = np.repeat(np.asarray([TONES_HZ[t] for t in symbols]), SAMPLES_PER_SYMBOL)
    phase = np.cumsum(2 * np.pi * freqs / sample_rate, dtype=np.float64)
    audio = level * np.sin(phase)
    if snr_db is not None:
        rms = level / math.sqrt(2)
        noise_rms = rms / 10 ** (snr_db / 20)
        audio += np.random.default_rng(seed).normal(0.0, noise_rms, len(audio))
    return np.pad(audio, (prepad_samples, 0))


def demod_tones(audio: np.ndarray, first_sample: int, n: int) -> tuple[int, ...]:
    if first_sample < 0 or first_sample + n * SAMPLES_PER_SYMBOL > len(audio):
        raise ValueError("insufficient samples")
    frame = np.asarray(audio[first_sample : first_sample + n * SAMPLES_PER_SYMBOL])
    frame = frame.reshape(n, SAMPLES_PER_SYMBOL)
    # Independent noncoherent discriminator: no knowledge of transmitted payload.
    fft = np.abs(np.fft.rfft(frame * np.hanning(SAMPLES_PER_SYMBOL), axis=1))
    return tuple(int(x) for x in np.argmax(fft[:, FFT_TONE_BINS], axis=1))


def recover_audio(audio: np.ndarray, *, search_samples: int = 768) -> tuple[bytes, int]:
    """Find whole-frame boundaries from public preamble/sync; require CRC.

    Search uses up to 96 start candidates at 8-sample granularity (1 ms).
    It does NOT grant weak-signal acquisition performance by itself.
    """
    start_count = len(PREAMBLE) + len(SYNC)
    max_start = min(search_samples, len(audio) - start_count * SAMPLES_PER_SYMBOL)
    if max_start < 0:
        raise ValueError("audio shorter than sync")
    last_error: ValueError = ValueError("no CRC-valid frame found")
    for start in range(0, max_start + 1, 8):
        head = demod_tones(audio, start, start_count + 9)
        if head[:start_count] != PREAMBLE + SYNC:
            continue
        try:
            prefix = head[start_count:]
            raw_length = majority3(*prefix[:3])
            # The first byte spans three triplicated tones.
            # Instead, demod the first nine data tones to recover 3 uncoded tones.
            tones = [majority3(*prefix[i:i + 3]) for i in (0, 3, 6)]
            bits = [bit for t in tones for bit in ((t >> 2) & 1, (t >> 1) & 1, t & 1)]
            length = bytes_from_bits(bits[:8])[0]
            if length > MAX_BYTES:
                continue
            needed = start_count + 3 * math.ceil((1 + length + 2) * 8 / 3)
            all_tones = demod_tones(audio, start, needed)
            return decode_symbols(all_tones), start
        except ValueError as exc:
            last_error = exc
    raise ValueError(f"no CRC-valid frame found: {last_error}")


def write_wav(path: Path, audio: np.ndarray) -> None:
    pcm = (np.clip(audio, -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SAMPLE_RATE)
        w.writeframes(pcm.tobytes())


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--message", default="CQ AG7SU CN85")
    p.add_argument("--snr-db", type=float, default=None, help="AWGN dB in audio samples (not RF SNR)")
    p.add_argument("--wav", type=Path)
    p.add_argument("--header", action="store_true", help="print 32-symbol radio fixture C header")
    args = p.parse_args()
    if args.header:
        print(fixture_header(), end="")
        return
    msg = args.message.encode("ascii")
    symbols = packet_symbols(msg)
    audio = render_audio(symbols, prepad_samples=91, snr_db=args.snr_db)
    if args.wav:
        write_wav(args.wav, audio)
    decoded, start = recover_audio(audio)
    print(json.dumps({
        "mode": "Flux Whisper8 v0 (not Olivia-compatible)",
        "payload": decoded.decode("ascii"), "symbols": len(symbols),
        "duration_s": len(symbols) / SYMBOL_RATE,
        "tone_hz": TONES_HZ, "reg71_words": [reg71_word(x) for x in TONES_HZ],
        "symbol_rate": SYMBOL_RATE, "sample_offset": start,
        "snr_db_audio": args.snr_db, "crc16_ok": decoded == msg
    }, indent=2))


if __name__ == "__main__":
    main()
